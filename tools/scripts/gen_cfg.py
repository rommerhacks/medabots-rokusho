#!/usr/bin/env python3
"""Generate the gbadisasm config: verified function seeds plus names from re/symbols.txt."""
import struct, sys, collections

ROM, SYMS, OUT = sys.argv[1:4]
rom = open(ROM, 'rb').read()
BASE = 0x08000000
CODE = [(0x0800025C, 0x080750D8), (0x0807C740, 0x0807E6F0)]

def in_code(a):
    return any(lo <= a < hi for lo, hi in CODE)

def hw(a):
    return struct.unpack_from('<H', rom, a - BASE)[0]

def is_push(a):
    return (hw(a) & 0xFE00) == 0xB400

# function pointers anywhere in the ROM (Thumb, odd)
seeds = {}
for off in range(0, len(rom) - 3, 4):
    w = struct.unpack_from('<I', rom, off)[0]
    if w & 1 and in_code(w & ~1) and is_push(w & ~1):
        seeds[w & ~1] = None

names = {}
for line in open(SYMS):
    p = line.split()
    if len(p) < 2:
        continue
    a = int(p[0], 16)
    if in_code(a) and a % 2 == 0 and is_push(a):
        names[a] = p[1]
        seeds[a] = None

cnt = collections.Counter(names.values())
out = ["# gbadisasm config for Medabots Rokusho (A9BE). Generated by tools/scripts/gen_cfg.py",
       "arm_func 0x80000c0 crt0_start f",
       "arm_func 0x8000104 irq_dispatch_arm f",
       "arm_func 0x8000218 link_buffer_swap_arm f",
       "thumb_func 0x800025c main f"]
for a in sorted(seeds):
    if a == 0x0800025C:
        continue
    n = names.get(a)
    if n is None:
        n = f"sub_{a:08X}"
    elif cnt[n] > 1:
        n = f"{n}_{a:08X}"
    out.append(f"thumb_func {a:#x} {n}")
open(OUT, 'w').write("\n".join(out) + "\n")
print(f"{len(seeds)} seeds, {len(names)} named", file=sys.stderr)
